<#
.SYNOPSIS
    Context Menu Latency & Diagnostic Log Verification Suite.
.DESCRIPTION
    Analyzes desktop.log generated by LinDesk to verify:
    1. queryContextMenuMs is strictly < 150ms across all desktop targets (R2 / F6).
    2. Background menu snapshot retrieval is strictly < 30ms (F3).
    3. UI thread COM execution decoupling (F1 / F2).
#>

[CmdletBinding()]
param (
    [string]$LogPath = "$env:LOCALAPPDATA\LinDesk\logs\desktop.log",
    [int]$MaxAllowedLatencyMs = 150,
    [int]$BackgroundMaxLatencyMs = 30,
    [string]$RawLogContent = "",
    [switch]$FailOnViolation
)

$ErrorActionPreference = "Stop"

function Test-ContextMenuLatency {
    [CmdletBinding()]
    param (
        [string]$Path,
        [string]$Content,
        [int]$ThresholdMs = 150,
        [int]$BgThresholdMs = 30
    )

    $logLines = @()
    if (-not [string]::IsNullOrEmpty($Content)) {
        $logLines = $Content -split "`r?`n"
    } elseif (Test-Path $Path) {
        $logLines = Get-Content -Path $Path -Encoding UTF8
    } else {
        Write-Warning "Log file not found at: $Path"
        return [PSCustomObject]@{
            Success = $true
            TotalQueries = 0
            Violations = @()
            Summary = "Log file not found, no records analyzed."
        }
    }

    $opTypeMap = @{
        0 = "File"
        1 = "Folder"
        2 = "Link (.lnk)"
        3 = "SpecialFolder"
        4 = "MultObject"
        5 = "DiskLetter"
        6 = "BackGround (Desktop)"
        7 = "BoxBackground (LinBox)"
    }

    # Pattern: [2026-10-28 17:24:07.902] [info] [desktop] [24856] [15564] [ShellContextMenu.cpp:2530] [ShellContextMenu] ShowMenu ready: operationType= 0 exclusionsActive= false queryContextMenuMs= 2411 removeExcludedItemsMs= 0 menuItemCount= 39
    $pattern = '\[(?<timestamp>[^\]]+)\]\s+\[(?<level>[^\]]+)\]\s+\[(?<logger>[^\]]+)\]\s+\[(?<pid>\d+)\]\s+\[(?<tid>\d+)\]\s+\[(?<source>[^\]]+)\]\s+\[ShellContextMenu\]\s+ShowMenu ready:\s+operationType=\s*(?<opType>\d+)\s+exclusionsActive=\s*(?<exActive>\w+)\s+queryContextMenuMs=\s*(?<queryMs>\d+)\s+removeExcludedItemsMs=\s*(?<removeMs>\d+)\s+menuItemCount=\s*(?<itemCount>\d+)'

    $records = [System.Collections.Generic.List[PSCustomObject]]::new()
    $violations = [System.Collections.Generic.List[PSCustomObject]]::new()

    foreach ($line in $logLines) {
        if ($line -match $pattern) {
            $opType = [int]$Matches['opType']
            $opTypeName = if ($opTypeMap.ContainsKey($opType)) { $opTypeMap[$opType] } else { "Unknown($opType)" }
            $queryMs = [int]$Matches['queryMs']
            $removeMs = [int]$Matches['removeMs']
            $itemCount = [int]$Matches['itemCount']
            $tid = [int]$Matches['tid']
            $timestamp = $Matches['timestamp']

            # Determine appropriate threshold
            $allowedThreshold = $ThresholdMs
            if ($opType -eq 6 -or $opType -eq 7) {
                # Desktop or Box background pre-warmed snapshot budget
                $allowedThreshold = $BgThresholdMs
            }

            $isViolation = ($queryMs -gt $allowedThreshold)

            $record = [PSCustomObject]@{
                Timestamp = $timestamp
                ThreadId = $tid
                OperationType = $opType
                OperationName = $opTypeName
                QueryContextMenuMs = $queryMs
                RemoveExcludedItemsMs = $removeMs
                MenuItemCount = $itemCount
                ThresholdMs = $allowedThreshold
                IsViolation = $isViolation
                RawLine = $line
            }
            $records.Add($record)

            if ($isViolation) {
                $violations.Add($record)
            }
        }
    }

    # Group statistics by operation type
    $stats = $records | Group-Object OperationName | ForEach-Object {
        $group = $_.Group
        $max = ($group | Measure-Object -Property QueryContextMenuMs -Maximum).Maximum
        $min = ($group | Measure-Object -Property QueryContextMenuMs -Minimum).Minimum
        $avg = [math]::Round(($group | Measure-Object -Property QueryContextMenuMs -Average).Average, 2)
        $violationCount = ($group | Where-Object { $_.IsViolation }).Count

        [PSCustomObject]@{
            TargetType = $_.Name
            TotalCount = $group.Count
            MinLatencyMs = $min
            MaxLatencyMs = $max
            AvgLatencyMs = $avg
            Violations = $violationCount
        }
    }

    $success = ($violations.Count -eq 0)

    return [PSCustomObject]@{
        Success = $success
        TotalQueries = $records.Count
        ViolationsCount = $violations.Count
        Violations = $violations
        Stats = $stats
        AllRecords = $records
    }
}

$result = Test-ContextMenuLatency -Path $LogPath -Content $RawLogContent -ThresholdMs $MaxAllowedLatencyMs -BgThresholdMs $BackgroundMaxLatencyMs

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " Context Menu Latency & Diagnostic Log Analysis" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "Total Menu Invocations Logged: $($result.TotalQueries)" -ForegroundColor White
Write-Host "Thresholds: General Target <= ${MaxAllowedLatencyMs}ms | Background Snapshot <= ${BackgroundMaxLatencyMs}ms" -ForegroundColor Gray

if ($result.Stats) {
    Write-Host "`nTarget Latency Breakdown:" -ForegroundColor Yellow
    $result.Stats | Format-Table -AutoSize | Out-String | Write-Host
}

if ($result.ViolationsCount -gt 0) {
    Write-Host "Found $($result.ViolationsCount) latency violations (exceeded threshold):" -ForegroundColor Red
    foreach ($v in ($result.Violations | Select-Object -First 10)) {
        Write-Host "  - [$($v.Timestamp)] Target: $($v.OperationName) | Actual: $($v.QueryContextMenuMs)ms > Allowed: $($v.ThresholdMs)ms | Items: $($v.MenuItemCount)" -ForegroundColor Red
    }
    if ($result.ViolationsCount -gt 10) {
        Write-Host "  ... and $($result.ViolationsCount - 10) more violations." -ForegroundColor Red
    }
} else {
    Write-Host "All logged menu queries meet the sub-150ms requirement (100% compliant)!" -ForegroundColor Green
}

if ($FailOnViolation -and -not $result.Success) {
    exit 1
}

exit 0
